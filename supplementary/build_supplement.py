def v2_sections():
    """Tables added in the revision: applications, fresh validation, near-copies, retrospective purity."""
    R = os.path.join(RES, "reinforcement")
    out = ["\n# R1 Applications (all learners)\n\nMeans over 10 random splits, LAC score, α = 0.1. `pi`, `pi_p`: "
           "exposure and label-pure exposure; `predicted_gap`: Eq. (3); coverages and set sizes on new cases.\n"]
    cs = pd.read_csv(os.path.join(R, "tables", "case_studies.csv"))
    out.append(md_table(cs[["application", "name", "model", "n_rows", "pi", "pi_p", "predicted_gap", "reported_cov",
                            "new_cov_standard", "new_cov_fixed", "seen_cov_standard", "size_new_standard",
                            "size_new_fixed"]]))
    sel = json.load(open(os.path.join(R, "prospective_selection.json")))
    out.append(f"\n# R2 Fresh validation set: selection log\n\nSelection date {sel['date']}; pool of {sel['pool_size']} "
               "OpenML data sets (studies 271, 269, 334–337). Inclusion used no labels and no models.\n\n## Included\n")
    out.append(md_table(pd.DataFrame(sel["included"])[["data_id", "name", "task", "n_raw", "n_rows", "subsampled",
                                                       "dup_row_frac", "pred_exposure"]]))
    out.append("\n## Excluded (with reason)\n")
    ex = pd.DataFrame(sel["excluded"])
    ex["reason"] = ex["excluded"].str.slice(0, 90)
    out.append(md_table(ex[["data_id", "name", "reason"]].fillna("")))
    pp = pd.read_csv(os.path.join(R, "tables", "prospective_per_dataset.csv"))
    out.append("\n# R3 Fresh validation: coverage on new cases per data set\n\nMeans over 20 random splits, α = 0.1, "
               "LAC (classification) or absolute residual (regression). `bad`: share of splits with new-case coverage "
               "below 0.87; `fallback`: share of splits in which too few new calibration rows existed.\n")
    out.append(md_table(pp.sort_values(["name", "model", "method"]), 3))
    st = json.load(open(os.path.join(R, "statistics_reinforcement.json")))
    for key, title in [("P1_P2_P5", "R4 Pre-specified tests P1, P2, P5"), ("P3", "R5 Pre-specified test P3"),
                       ("P4", "R6 Pre-specified test P4"), ("normres", "R7 Normalized-residual score on fresh regression data")]:
        if key in st:
            df = pd.DataFrame(st[key])
            for c in df.columns:
                if df[c].map(lambda v: isinstance(v, (list, dict))).any():
                    df[c] = df[c].map(lambda v: str(v)[:80])
            out.append(f"\n# {title}\n")
            out.append(md_table(df, 4))
    out.append(f"\nHolm-adjusted primary p-values: {st.get('holm_primary')}.\n")
    out.append("\n# R8 Near-copies: median gap on truly new rows (pp/100) by noise level\n")
    out.append(md_table(pd.read_csv(os.path.join(R, "tables", "neardup_summary.csv")), 4))
    out.append("\n# R9 Retrospective test of Eq. (3) (non-blind)\n")
    out.append(md_table(pd.DataFrame([{k: v for k, v in x.items() if k != "violations"} for x in st["retrospective"]]), 4))
    out.append("\n# R10 Reinforcement protocol and deviations\n")
    prot = open(os.path.join(ROOT, "reinforcement", "research_design", "revised_experimental_protocol.md")).read()
    out.append(prot.split("\n", 1)[1].replace("\n# ", "\n## "))
    return out


def main(version="v1"):
    S = json.load(open(os.path.join(RES, "statistics.json")))
    out = [f"---\ntitle: \"{TITLE_V2 if version == 'v2' else TITLE_V1}\"\n---\n",
           "All tables are generated by `supplementary/build_supplement.py` from the result files in `results/`. "
           "Coverage gaps are in proportions (multiply by 100 for percentage points).\n"]
    a = pd.read_csv(os.path.join(T, "T1_audit.csv"))
    a = a[["task", "data_id", "name", "n_rows", "n_raw", "n_features", "n_classes", "dup_row_frac",
           "conflict_row_frac", "max_group", "pred_exposure", "obs_exposure", "set"]].sort_values(["task", "pred_exposure"], ascending=[True, False])
    out.append("# S1 Dataset audit\n\nOne row per dataset (OpenML data ID). `n_raw`: rows before group-preserving subsampling to 30,000. "
               "`dup_row_frac`: share of rows in a group of identical feature vectors of size ≥ 2. `conflict_row_frac`: share of rows in groups "
               "with more than one label. `pred_exposure`: Proposition 2. `obs_exposure`: mean over 10 random splits. "
               "`set`: DUP (π̄ ≥ 0.01), LOW (0 < π̄ < 0.01), CLEAN (no duplicates).\n")
    out.append(md_table(a))
    out.append("\n# S2 Protocol deviations and post-hoc analyses\n")
    dev = open(os.path.join(ROOT, "research_design", "protocol_deviations.md")).read().split("\n", 2)[2]
    out.append(dev)
    for alpha in ("0.05", "0.1", "0.2"):
        k = f"main_alpha_{alpha}"
        if k not in S:
            continue
        M = pd.DataFrame(S[k])[["task", "model", "score", "n_datasets", "scp_all_cov_median", "scp_seen_cov_median",
                                "scp_novel_cov_median", "scp_gap_median", "scp_gap_min", "p_H1_holm", "spearman_exposure_gap",
                                "p_spearman", "mcp_all_cov_median", "mcp_novel_cov_median", "mcp_gap_ci_lo", "p_H2_holm",
                                "size_ratio_novel_median", "size_ratio_seen_median", "size_ratio_all_median"]]
        out.append(f"\n# S3{'abc'[('0.05', '0.1', '0.2').index(alpha)]} Main results on DUP datasets, α = {alpha}\n\n"
                   "Medians over datasets of seed-averaged metrics; split CP with a random split (scp) and novelty-Mondrian CP (mcp).\n")
        out.append(md_table(M))
    out.append("\n# S4 Group-aware split (SCP-G), α = 0.1\n")
    out.append(md_table(pd.DataFrame(S["H6_group_split"])))
    out.append("\n# S5 Null control (CLEAN datasets), α = 0.1\n")
    out.append(md_table(pd.DataFrame(S["null_control"])))
    out.append("\n# S6 Friedman tests across learners (novel coverage, SCP-R, DUP)\n")
    fr = []
    for k, v in S["H1b_friedman"].items():
        fr.append(dict(family=k, n=v["n"], chi2=v["chi2"], p=v["p"],
                       **{f"median_{m}": c for m, c in v["median_novel_cov"].items()}))
    out.append(md_table(pd.DataFrame(fr), 4))
    out.append("\n# S7 Exploratory exposure strata\n")
    out.append(md_table(pd.read_csv(os.path.join(T, "X2_exposure_strata.csv")), 4))
    out.append("\n# S8 Verification run on solar_flare (200 additional splits)\n")
    vf = json.load(open(os.path.join(RES, "verification", "solar_flare_200splits.json")))
    out.append(md_table(pd.DataFrame([dict(model=k, **{kk: (str([round(x, 4) for x in vv]) if isinstance(vv, list) else vv)
                                                      for kk, vv in v.items()}) for k, v in vf.items()]), 4))
    for key, name, xv in [("D_injection", "S9 Duplicate injection: medians by rate", "rate"),
                          ("F_capacity", "S10 Capacity: medians by level", "level")]:
        if key in S:
            rows = []
            for k, v in S[key].items():
                for r in v["by_level"]:
                    rows.append(dict(family=k, **r))
            out.append(f"\n# {name}\n\n`gap`/`mcp_gap`: novel-record coverage − 0.9 for split / novelty-Mondrian CP; "
                       "`limit_gap`: memorization limit −απ/(1−π).\n")
            out.append(md_table(pd.DataFrame(rows), 4))
    nb = os.path.join(T, "T11_normalized_baseline.csv")
    if os.path.exists(nb):
        out.append("\n# S10b Normalized-residual baseline (regression DUP datasets, alpha = 0.1)\n\nMean over 10 splits. "
                   "Score |y - yhat| / (sigma(x) + beta), sigma = mean distance to 10 nearest training rows.\n")
        out.append(md_table(pd.read_csv(nb), 4))
    out.append("\n# S11 Computational cost (Experiment G)\n")
    out.append(md_table(pd.read_csv(os.path.join(T, "T9_cost.csv")), 4))
    out.append("\n# Fig. S1\n\n![**Fig. S1** Novel-record coverage gap per duplicated dataset (dots) and learner, split CP vs novelty-Mondrian CP, alpha = 0.1; bars: medians](FigS1.png)\n")
    out.append("\n# S12 Computational environment\n")
    env = json.load(open(os.path.join(RES, "logs", "environment.json")))
    out.append(md_table(pd.DataFrame([env]).T.reset_index().rename(columns={"index": "item", 0: "value"})))
    if version == "v2":
        out += v2_sections()
    stem = "Supplementary_Material_v2" if version == "v2" else "Online_Resource_1"
    md = "\n".join(out)
    p_md = os.path.join(HERE, f"{stem}.md")
    open(p_md, "w").write(md)
    figs = os.path.join(RES, "figures")
    subprocess.run(["pandoc", p_md, "-o", os.path.join(HERE, f"{stem}.docx"), "--resource-path", figs], check=True)
    html = os.path.join(HERE, f"{stem}.html")
    css = os.path.join(HERE, "supp.css")
    subprocess.run(["pandoc", p_md, "-s", "--embed-resources", "--css", css, "--metadata", "lang=en",
                    "--resource-path", figs, "-o", html], check=True)
    chrome = os.environ.get("CHROME", "/opt/pw-browsers/chromium-1194/chrome-linux/chrome")
    subprocess.run([chrome, "--headless", "--no-sandbox", "--disable-gpu", "--no-pdf-header-footer",
                    f"--print-to-pdf={os.path.join(HERE, stem + '.pdf')}", "file://" + html],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    os.remove(html)
    print("ok")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "v1")
