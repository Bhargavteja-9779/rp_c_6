"""Write data_links.tex: a link to the source page of every data set used in the study.

Built only from the study's own records (results/dataset_list.json, the audit files and the
time-stamped selection logs of the two fresh collections), so the list matches what was analysed.
Usage: python3 tools/make_data_links.py   (run from paper_pr/ or anywhere)
"""
import json, os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(HERE)
RES = os.path.join(ROOT, "results")
OML, UCI = "https://www.openml.org/d/", "https://archive.ics.uci.edu/dataset/"


def tex(s):
    for a, b in [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#"),
                 ("$", "\\$"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde{}"), ("^", "\\^{}")]:
        s = s.replace(a, b)
    return s


def name_of(task, did, folder="raw"):
    return json.load(open(os.path.join(RES, folder, f"audit_{task}_{did}.json")))["name"]


def items(pairs, base):
    return "; ".join(f"\\href{{{base}{i}}}{{{tex(n)}~({i})}}" for n, i in pairs) + "."


bench = json.load(open(os.path.join(RES, "dataset_list.json")))
cls = sorted(((name_of(t, i), i) for t, i in bench if t == "classification"), key=lambda x: x[0].lower())
reg = sorted(((name_of(t, i), i) for t, i in bench if t == "regression"), key=lambda x: x[0].lower())
apps_raw = [1067, 1063, 1068, 1050, 1049, 1053, 4534]           # application sets that are also in OpenML-CC18
apps_ext = [1056, 1069, 1065, 1071, 1113]                        # application sets added from outside the suites
apps = [(name_of("classification", i), i) for i in apps_raw] + \
       [(name_of("classification", i, "external"), i) for i in apps_ext]
w1 = json.load(open(os.path.join(RES, "reinforcement", "prospective_selection.json")))["included"]
w2 = json.load(open(os.path.join(RES, "reinforcement", "prospective_selection_w2.json")))["included"]
w1p = sorted(((x["name"], x["data_id"]) for x in w1), key=lambda x: x[0].lower())
w2p = sorted(((x["name"], x["uci_id"]) for x in w2), key=lambda x: x[0].lower())
assert len(bench) == 103 and len(apps) == 12 and len(w1p) == 20 and len(w2p) == 27

out = [
    "% generated by tools/make_data_links.py -- do not edit by hand",
    "Every data set used in the study, with a link to its source page. OpenML data sets are at "
    f"\\url{{{OML}<ID>}} and UCI data sets at \\url{{{UCI}<ID>}}; the identifier is given in parentheses and "
    "each entry is a link. The suites are OpenML-CC18 (\\url{https://www.openml.org/s/99}), "
    "OpenML-CTR23 (\\url{https://www.openml.org/s/353}), the AutoML Benchmark "
    "(\\url{https://www.openml.org/s/271} and \\url{https://www.openml.org/s/269}) and the benchmark of "
    "Grinsztajn et al.\\ (OpenML suites 334--337).",
    "",
    "{\\small\\raggedright",
    f"\\paragraph{{Applications ({len(apps)}, OpenML).}} " + items(apps, OML),
    "",
    f"\\paragraph{{Benchmarks, classification ({len(cls)}, OpenML-CC18).}} " + items(cls, OML),
    "",
    f"\\paragraph{{Benchmarks, regression ({len(reg)}, OpenML-CTR23).}} " + items(reg, OML),
    "",
    f"\\paragraph{{Fresh collection, wave 1 ({len(w1p)}, OpenML).}} " + items(w1p, OML),
    "",
    f"\\paragraph{{Fresh collection, wave 2 ({len(w2p)}, UCI).}} " + items(w2p, UCI),
    "\\par}",
    "",
]
open(os.path.join(HERE, "data_links.tex"), "w", encoding="utf-8").write("\n".join(out))
print("data_links.tex:", len(apps), len(cls), len(reg), len(w1p), len(w2p))
